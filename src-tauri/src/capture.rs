//! Evidence taken when someone unlocks or fails to: every monitor plus one webcam frame, saved as JPEG.
//! Failures never block the unlock; they are reported as notes and stored on the event.
use image::{codecs::jpeg::JpegEncoder, DynamicImage, RgbImage};
use std::{
    fs::{self, File},
    io::BufWriter,
    path::Path,
    sync::mpsc,
    thread,
    time::Duration,
};

const JPEG_QUALITY: u8 = 75;
const WEBCAM_WARMUP_FRAMES: usize = 10;
const WEBCAM_BUDGET: Duration = Duration::from_secs(10);

#[derive(Debug, Default)]
pub struct Capture {
    pub files: Vec<String>,
    /// Human-readable reasons for whatever could not be captured.
    pub notes: Vec<String>,
}

pub trait Capturer: Send {
    fn capture(&mut self, dir: &Path, id: &str) -> Capture;
}

pub struct SystemCapturer;

impl Capturer for SystemCapturer {
    fn capture(&mut self, dir: &Path, id: &str) -> Capture {
        let mut out = Capture::default();
        match screens(dir, id) {
            Ok(files) => out.files.extend(files),
            Err(e) => out.notes.push(format!("tela: {e}")),
        }
        match webcam(dir, id) {
            Ok(file) => out.files.push(file),
            Err(e) => out.notes.push(format!("webcam: {e}")),
        }
        out
    }
}

fn save_jpeg(img: &RgbImage, path: &Path) -> Result<(), String> {
    let file = File::create(path).map_err(|e| e.to_string())?;
    JpegEncoder::new_with_quality(BufWriter::new(file), JPEG_QUALITY).encode_image(img).map_err(|e| e.to_string())
}

fn screens(dir: &Path, id: &str) -> Result<Vec<String>, String> {
    let monitors = xcap::Monitor::all().map_err(|e| e.to_string())?;
    let mut files = Vec::new();
    for (n, monitor) in monitors.iter().enumerate() {
        let img = monitor.capture_image().map_err(|e| e.to_string())?;
        let name = format!("{id}-screen{n}.jpg");
        save_jpeg(&DynamicImage::ImageRgba8(img).to_rgb8(), &dir.join(&name))?;
        files.push(name);
    }
    if files.is_empty() {
        return Err("nenhum monitor encontrado".into());
    }
    Ok(files)
}

fn grab_frame() -> Result<RgbImage, String> {
    use nokhwa::{
        pixel_format::RgbFormat,
        utils::{CameraIndex, RequestedFormat, RequestedFormatType},
        Camera,
    };
    let format = RequestedFormat::new::<RgbFormat>(RequestedFormatType::AbsoluteHighestFrameRate);
    let mut camera = Camera::new(CameraIndex::Index(0), format).map_err(|e| e.to_string())?;
    camera.open_stream().map_err(|e| e.to_string())?;
    // Webcams return dark frames until auto-exposure settles.
    for _ in 0..WEBCAM_WARMUP_FRAMES {
        camera.frame().map_err(|e| e.to_string())?;
    }
    let decoded = camera.frame().map_err(|e| e.to_string())?.decode_image::<RgbFormat>().map_err(|e| e.to_string())?;
    let (w, h) = (decoded.width(), decoded.height());
    RgbImage::from_raw(w, h, decoded.into_raw()).ok_or_else(|| "quadro da webcam inconsistente".to_string())
}

fn webcam(dir: &Path, id: &str) -> Result<String, String> {
    // A busy or hung driver must not hold the unlock: give up after the budget and leave the thread to die.
    let (tx, rx) = mpsc::channel();
    thread::spawn(move || {
        let _ = tx.send(grab_frame());
    });
    let img = rx.recv_timeout(WEBCAM_BUDGET).map_err(|_| "tempo esgotado (câmera ocupada ou sem resposta)".to_string())??;
    let name = format!("{id}-cam.jpg");
    save_jpeg(&img, &dir.join(&name))?;
    Ok(name)
}

/// Shot names are generated by `capture`; anything else (path separators, `..`, odd suffixes) is refused.
pub fn valid_name(name: &str) -> bool {
    let Some(stem) = name.strip_suffix(".jpg") else { return false };
    let Some((id, kind)) = stem.rsplit_once('-').filter(|(id, _)| id.len() == 36) else { return false };
    let id_ok = id.bytes().all(|b| b.is_ascii_hexdigit() && !b.is_ascii_uppercase() || b == b'-');
    id_ok && (kind == "cam" || kind.strip_prefix("screen").is_some_and(|n| !n.is_empty() && n.bytes().all(|b| b.is_ascii_digit())))
}

pub fn read(dir: &Path, name: &str) -> Result<Vec<u8>, String> {
    if !valid_name(name) {
        return Err("nome de captura inválido".into());
    }
    fs::read(dir.join(name)).map_err(|e| e.to_string())
}

pub fn remove(dir: &Path, names: &[String]) {
    for name in names.iter().filter(|n| valid_name(n)) {
        let _ = fs::remove_file(dir.join(name));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const ID: &str = "0b1c2d3e-4f50-4a6b-8c7d-9e0f1a2b3c4d";

    #[test]
    fn only_generated_names_are_readable() {
        for ok in [format!("{ID}-cam.jpg"), format!("{ID}-screen0.jpg"), format!("{ID}-screen12.jpg")] {
            assert!(valid_name(&ok), "{ok}");
        }
        for bad in [
            "..\\config.json", "../x-cam.jpg", &format!("{ID}-cam.png"), &format!("{ID}-screen.jpg"), &format!("{ID}-screenx.jpg"),
            &format!("..{ID}-cam.jpg"), &format!("{}-cam.jpg", ID.to_uppercase()), "x-cam.jpg", "", &format!("{ID}\\..\\a-cam.jpg"),
        ] {
            assert!(!valid_name(bad), "{bad:?} was accepted");
        }
    }

    #[test]
    fn read_refuses_traversal_even_when_the_target_exists() {
        let dir = tempfile::tempdir().unwrap();
        fs::write(dir.path().join("config.json"), "secret").unwrap();
        fs::create_dir(dir.path().join("shots")).unwrap();
        assert!(read(&dir.path().join("shots"), "..\\config.json").is_err());
        assert!(read(&dir.path().join("shots"), "../config.json").is_err());
    }

    #[test]
    fn saved_frames_decode_back_as_jpeg() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join(format!("{ID}-cam.jpg"));
        save_jpeg(&RgbImage::from_pixel(32, 24, image::Rgb([200, 10, 10])), &path).unwrap();
        let back = image::open(&path).unwrap();
        assert_eq!((back.width(), back.height()), (32, 24));
        assert_eq!(read(dir.path(), &format!("{ID}-cam.jpg")).unwrap()[..2], [0xff, 0xd8]);
    }

    /// Real hardware: `cargo test --lib smoke_capture -- --ignored --nocapture`. Writes into a temp dir, or PORTEIRO_SMOKE_DIR.
    #[test]
    #[ignore = "needs a screen and a webcam"]
    fn smoke_capture() {
        let tmp = tempfile::tempdir().unwrap();
        let dir = std::env::var_os("PORTEIRO_SMOKE_DIR").map(std::path::PathBuf::from).unwrap_or_else(|| tmp.path().to_path_buf());
        let out = SystemCapturer.capture(&dir, ID);
        for f in &out.files {
            println!("{f}: {} bytes", fs::metadata(dir.join(f)).unwrap().len());
        }
        println!("notes: {:?}", out.notes);
        assert!(out.files.iter().any(|f| f.contains("screen")), "no screen capture: {:?}", out.notes);
        assert!(out.files.iter().any(|f| f.ends_with("-cam.jpg")), "no webcam frame: {:?}", out.notes);
    }
}
